<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Str;

class Customer extends Model
{
    use HasFactory;

    protected $fillable = [
        'member_code',
        'unique_code',
        'name',
        'phone',
        'address',
        'joined_at',
        'last_portal_access',
    ];

    protected $casts = [
        'joined_at' => 'datetime',
    ];

    /**
     * Memoised ledger balance. Not a column — purely a per-instance cache so a
     * view that reads `$customer->balance` repeatedly pays for one query.
     */
    protected ?float $balanceCache = null;

    /**
     * Clear the memoised balance whenever the model is re-hydrated or refreshed,
     * otherwise a stale value would survive a ledger change.
     */
    public function refresh()
    {
        $this->balanceCache = null;

        return parent::refresh();
    }

    /**
     * Boot the model.
     */
    protected static function boot()
    {
        parent::boot();

        // Auto-generate member_code and unique_code before creating if not provided
        static::creating(function ($customer) {
            if (empty($customer->member_code)) {
                $customer->member_code = static::generateNextMemberCode();
            }

            if (empty($customer->unique_code)) {
                $customer->unique_code = static::generateUniqueCode();
            }
        });
    }

    /**
     * Save the model, retrying when an auto-generated member code collides.
     *
     * `member_code` is generated by reading the newest row and adding one. That
     * read-then-write is not atomic, so two concurrent inserts can compute the same
     * code and the unique index rejects the second one. Retrying is the only
     * reliable fix: there is no row to lock when the table is still empty.
     *
     * On a collision the sequence is incremented monotonically rather than
     * recomputed from the table. Recomputing would return the same value while the
     * competing row is still uncommitted, so the retry could fail forever; bumping
     * guarantees forward progress.
     *
     * A `member_code` supplied by the caller is never bumped, so genuine duplicates
     * still surface as an error instead of being silently renumbered.
     *
     * `unique_code` needs no retry here: it is drawn from a 36^12 keyspace and
     * `generateUniqueCode()` already loops until `exists()` returns false.
     *
     * Note: this relies on the driver keeping the connection usable after a failed
     * statement (SQLite and MySQL both do). PostgreSQL aborts the surrounding
     * transaction instead, which would need a savepoint per attempt.
     */
    public function save(array $options = [])
    {
        if ($this->exists || ! empty($this->member_code)) {
            return parent::save($options);
        }

        // A caller-supplied unique_code must survive a retry untouched.
        $autoUniqueCode = empty($this->unique_code);
        $maxAttempts = 3;

        for ($attempt = 1; $attempt <= $maxAttempts; $attempt++) {
            try {
                return parent::save($options);
            } catch (UniqueConstraintViolationException $e) {
                if ($attempt === $maxAttempts) {
                    throw $e;
                }

                // `creating` has run, so member_code now holds the collided value.
                $this->member_code = static::incrementMemberCode($this->member_code);

                if ($autoUniqueCode) {
                    // Clear so `creating` draws a fresh random code on the retry.
                    $this->unique_code = null;
                }
            }
        }

        // Unreachable: the loop either returns or throws.
        throw new \RuntimeException('Gagal menyimpan nasabah dengan kode anggota unik.');
    }

    /**
     * Add one to the numeric suffix of a member code, keeping at least 4 digits.
     */
    private static function incrementMemberCode(?string $code): string
    {
        $number = preg_match('/(\d+)$/', (string) $code, $matches) ? (int) $matches[1] : 0;

        return 'CUST-'.str_pad($number + 1, 4, '0', STR_PAD_LEFT);
    }

    /**
     * Generate next member code (sequential, for admin/internal use)
     */
    private static function generateNextMemberCode(): string
    {
        // Order by id rather than by code: codes are zero-padded to 4 digits but
        // grow beyond 9999, so a string sort would misorder CUST-10000 vs CUST-9999.
        $lastCustomer = static::orderBy('id', 'desc')->first();

        if (! $lastCustomer) {
            return 'CUST-0001';
        }

        // Extract number from last code using regex (handles CUST-xxxx or any other format)
        preg_match('/(\d+)$/', (string) $lastCustomer->member_code, $matches);

        if (isset($matches[1])) {
            $lastNumber = (int) $matches[1];
        } else {
            // Fallback: use the ID as base
            $lastNumber = $lastCustomer->id;
        }

        $nextNumber = $lastNumber + 1;

        // Use minimum 4 digits, but allow expansion beyond 9999
        return 'CUST-'.str_pad($nextNumber, 4, '0', STR_PAD_LEFT);
    }

    /**
     * 🔒 Generate secure random unique code (for portal public access)
     * Format: BSB-XXXXXXXXXXXX (12 random chars)
     * Total kombinasi: 36^12 = 4,738,381,338,321,616,896
     */
    public static function generateUniqueCode(): string
    {
        do {
            // Cryptographically secure random string
            $code = 'BSB-'.strtoupper(Str::random(12));

            // Check collision (very unlikely, but safety first)
        } while (static::where('unique_code', $code)->exists());

        return $code;
    }

    /**
     * Whether this customer owns financial history that must never be deleted.
     */
    public function hasTransactions(): bool
    {
        return $this->deposits()->exists()
            || $this->withdrawals()->exists()
            || $this->ledgerEntries()->exists();
    }

    /**
     * Get deposits for this customer
     */
    public function deposits()
    {
        return $this->hasMany(Deposit::class);
    }

    /**
     * Get withdrawals for this customer
     */
    public function withdrawals()
    {
        return $this->hasMany(Withdrawal::class);
    }

    /**
     * Get ledger entries for this customer
     */
    public function ledgerEntries()
    {
        return $this->hasMany(LedgerEntry::class);
    }

    /**
     * Calculate customer balance from ledger entries.
     *
     * Balance is never stored — it is always derived from the ledger (see
     * docs/PROJECT.md §2). Two optimisations matter here:
     *
     * 1. The sum is done in SQL. The previous version pulled every ledger row into
     *    PHP and summed it, so a customer with 500 transactions cost 500 hydrations
     *    per balance read.
     * 2. The result is memoised per model instance, because a single view often
     *    reads `$customer->balance` several times.
     *
     * When the ledger was eager loaded with a `withSum` alias, that precomputed
     * value wins so a list of N customers costs one query instead of N.
     */
    public function getBalanceAttribute(): float
    {
        // Precomputed by `withAggregate()`; avoids one query per row in lists.
        if (array_key_exists('ledger_sum_signed', $this->attributes)) {
            return round((float) $this->attributes['ledger_sum_signed'], 2);
        }

        if ($this->balanceCache !== null) {
            return $this->balanceCache;
        }

        $balance = $this->ledgerEntries()
            ->selectRaw(LedgerEntry::BALANCE_SUM_SQL.' as balance')
            ->value('balance');

        return $this->balanceCache = round((float) $balance, 2);
    }

    /**
     * Ledger entries with a running balance attached, newest first.
     *
     * The running balance is computed in SQL with a window function, so only the
     * requested page crosses the wire while every row still shows the true balance
     * at that point in time.
     *
     * The window runs over the customer's *entire* ledger inside a subquery, then
     * the type filter is applied outside. Filtering first would make the balance
     * column drift: a page of deposits only would accumulate deposits and ignore
     * withdrawals, which is not what a running balance means.
     *
     * `running_balance` on each entry is the balance *after* that entry.
     *
     * Requires window-function support: SQLite 3.25+, MySQL 8+, MariaDB 10.2+,
     * PostgreSQL 8.4+. The app targets SQLite and MySQL 8, both fine.
     *
     * @return \Illuminate\Database\Eloquent\Builder<LedgerEntry>
     */
    public function ledgerWithRunningBalance(?string $refType = null)
    {
        $withBalance = LedgerEntry::query()
            ->select('ledger_entries.*')
            ->selectRaw(
                'SUM('.LedgerEntry::SIGNED_AMOUNT_SQL.') OVER (ORDER BY created_at, id ROWS UNBOUNDED PRECEDING) as running_balance'
            )
            ->where('customer_id', $this->getKey());

        return LedgerEntry::query()
            ->fromSub($withBalance, 'ledger_entries')
            ->with('referenceable')
            ->when($refType, fn ($q) => $q->where('ref_type', $refType))
            ->orderByDesc('created_at')
            ->orderByDesc('id');
    }

    /**
     * Get recent transactions
     */
    public function recentTransactions($limit = 10)
    {
        return $this->ledgerEntries()
            ->with(['referenceable'])
            ->latest()
            ->limit($limit)
            ->get();
    }
}
