<?php

namespace App\Http\Controllers;

use App\Http\Requests\StoreCustomerRequest;
use App\Http\Requests\UpdateCustomerRequest;
use App\Models\Customer;
use App\Models\LedgerEntry;
use Illuminate\Database\QueryException;
use Illuminate\Foundation\Auth\Access\AuthorizesRequests;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

class CustomerController extends Controller
{
    use AuthorizesRequests;

    /**
     * Display a listing of the resource.
     */
    public function index(Request $request)
    {
        $this->authorize('viewAny', Customer::class);

        $query = Customer::query();

        // Search functionality
        if ($request->has('search') && $request->search) {
            $search = $request->search;
            $query->where(function ($q) use ($search) {
                $q->where('name', 'like', "%{$search}%")
                    ->orWhere('member_code', 'like', "%{$search}%")
                    ->orWhere('phone', 'like', "%{$search}%");
            });
        }

        $customers = $query
            // Balance is derived from the ledger, not stored. Aggregate it in the
            // same query so the list costs one query instead of one per row.
            ->withAggregate('ledgerEntries as ledger_sum_signed', LedgerEntry::BALANCE_SUM_SQL)
            ->latest()
            ->paginate(15);

        return view('customers.index', compact('customers'));
    }

    /**
     * Show the form for creating a new resource.
     */
    public function create()
    {
        $this->authorize('create', Customer::class);

        // Don't generate code here to avoid race condition
        // Code will be generated during store
        $nextMemberCode = 'Auto-generated';

        return view('customers.create', compact('nextMemberCode'));
    }

    /**
     * Store a newly created resource in storage.
     */
    public function store(StoreCustomerRequest $request)
    {
        $data = $request->validated();

        // Use database transaction to ensure atomic operation
        $customer = DB::transaction(function () use ($data) {
            // member_code will be auto-generated by the model if not provided
            return Customer::create($data);
        });

        return redirect()->route('customers.index')
            ->with('success', 'Nasabah berhasil ditambahkan.');
    }

    /**
     * Display the specified resource.
     */
    public function show(Customer $customer)
    {
        $this->authorize('view', $customer);

        $customer->load([
            'deposits' => fn ($q) => $q->latest()->limit(10),
            'withdrawals' => fn ($q) => $q->latest()->limit(10),
        ]);

        // Running balance is computed in SQL, and only 20 rows are fetched. The
        // previous version loaded the whole ledger twice — once in the controller
        // and again inside the Blade template — to accumulate balances in PHP.
        $entries = $customer->ledgerWithRunningBalance()->limit(20)->get();

        return view('customers.show', compact('customer', 'entries'));
    }

    /**
     * Show the form for editing the specified resource.
     */
    public function edit(Customer $customer)
    {
        $this->authorize('update', $customer);

        return view('customers.edit', compact('customer'));
    }

    /**
     * Update the specified resource in storage.
     */
    public function update(UpdateCustomerRequest $request, Customer $customer)
    {
        $customer->update($request->validated());

        return redirect()->route('customers.index')
            ->with('success', 'Data nasabah berhasil diperbarui.');
    }

    /**
     * Remove the specified resource from storage.
     */
    public function destroy(Customer $customer)
    {
        $this->authorize('delete', $customer);

        if ($customer->hasTransactions()) {
            return redirect()->route('customers.index')
                ->with('error', 'Nasabah tidak dapat dihapus karena sudah memiliki transaksi. Data historis harus dipertahankan.');
        }

        try {
            $customer->delete();
        } catch (QueryException $exception) {
            report($exception);

            return redirect()->route('customers.index')
                ->with('error', 'Nasabah tidak dapat dihapus karena masih terhubung dengan data transaksi.');
        }

        return redirect()->route('customers.index')
            ->with('success', 'Nasabah berhasil dihapus.');
    }
}
